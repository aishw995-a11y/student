export function buildSampleStudentRecords(): StudentRecord[] {
  const now = Date.now();
  return rawDemoStudents.map(({ input, daysAgo }) => {
    const prediction = calculateWeightedDropoutRisk(input);
    const analyzedAt = new Date(now - daysAgo * 86_400_000).toISOString();
    return {
      ...input,
      id: input.studentId,
      prediction: {
        ...prediction,
        analyzedAt,
      },
    };
  });
}

